import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import test from 'node:test';
const src=readFileSync(new URL('../src/tasks/ClosingAnalysisFlow.tsx',import.meta.url),'utf8');
const render=readFileSync(new URL('../src/tasks/renderers.tsx',import.meta.url),'utf8');
test('both preliminary answers must lead to the entire applicable legal questionnaire',()=>{
  assert.match(src,/stage="Classificação preliminar"/);
  assert.match(src,/onChange=\{value => \{ setPreliminaryAgreed\(value\)/);
  assert.match(src,/stage="Cadastro de Sentença"/);
  assert.match(src,/Houve interposição de apelação\?/);
  assert.match(src,/Esse processo já transitou em julgado\?/);
  assert.match(src,/Custas foram pagas\?/);
  assert.match(src,/Houve pedido de execução\?/);
  assert.match(src,/Qual foi a data do trânsito em julgado\?/);
  assert.match(src,/Houve pagamento do valor integral solicitado pela autora\?/);
  assert.match(src,/preliminaryAvailable \? 7 : 5/);
  assert.match(src,/preliminary_classification_agreed: preliminaryAgreed === 'sim'/);
  assert.match(src,/classificationAgreed === null/);
  assert.match(src,/preliminaryAvailable && preliminaryAgreed === null/);
  assert.doesNotMatch(src,/ClosingPreclassificationFlow/);
  assert.doesNotMatch(src,/workflow_version: 6/);
  assert.match(render,/classifierReason=\{closingClassifierReason\(process\)\}/);
});
