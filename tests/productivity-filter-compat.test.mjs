import assert from 'node:assert/strict';
import ts from 'typescript';
import {readFileSync} from 'node:fs';
const source=readFileSync(new URL('../src/tasks/productivityFilters.ts',import.meta.url),'utf8');
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {normalizeProductivityFilters,productivityParams}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
const repaired=normalizeProductivityFilters({period:'30',deadline:'all',person:'all',module:'encerramento',day:'2026-10-26',inicio:'2026-10-01',fim:'2026-10-26'});
assert.deepEqual(repaired,{period:'30',deadline:'all',person:'all'});
const params=productivityParams(repaired,true,false);
assert.deepEqual([...params.keys()].sort(),['deadline','duration','include_growth','include_pending','period','person'].sort());
assert.equal(params.get('include_growth'),'0');
assert.equal(productivityParams(repaired,true,true).has('include_growth'),false);
assert.deepEqual(normalizeProductivityFilters({period:'x',deadline:'all',person:'malformed-id'}),{period:'30',deadline:'all',person:'all'});
assert.equal(productivityParams(repaired,false,false).get('person'),'all');
const page=readFileSync(new URL('../src/tasks/TaskResults.tsx',import.meta.url),'utf8');
assert.match(page,/normalizeProductivityFilters\(JSON\.parse/);
assert.match(page,/productivityParams\(filters,canViewOthers,false\)/);
assert.doesNotMatch(page,/URLSearchParams\(\{\s*\.\.\.filters/);
console.log('Produtividade: filtros legados saneados, escopo preservado, API sem parâmetros desconhecidos.');
