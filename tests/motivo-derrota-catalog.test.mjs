import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const renderer = readFileSync(new URL('../src/tasks/renderers.tsx', import.meta.url), 'utf8');
const results = readFileSync(new URL('../src/tasks/TaskResults.tsx', import.meta.url), 'utf8');
const menu = readFileSync(new URL('../src/dashboard/SelectMenu.tsx', import.meta.url), 'utf8');
assert.ok(renderer.includes('/api/motivo-derrota/catalog'));
assert.ok(renderer.includes('motivo_codigo: id, natureza'));
assert.ok(renderer.includes('SelectMenu label="Motivo da derrota" searchable'));
assert.ok(renderer.includes('Natureza da derrota'));
assert.ok(renderer.includes('Processual'));
assert.ok(renderer.includes('Voluntário'));
assert.ok(!renderer.includes('motivo-derrota-texto-'));
assert.ok(!renderer.includes('motivo-derrota-answer'));
assert.ok(renderer.includes("job?.status === 'ENVIADO'"));
assert.ok(results.includes('Motivo derrota'));
assert.ok(results.includes("status=' + motivoFilter"));
assert.ok(results.includes("Não — ausente confirmado"));
assert.ok(results.includes('registros não verificados ficam fora deste filtro'));
assert.ok(menu.includes('searchPlaceholder?: string'));
const workflow = readFileSync(new URL('../src/tasks/TaskQuestion.tsx', import.meta.url), 'utf8');
const station = readFileSync(new URL('../src/tasks/taskStation.css', import.meta.url), 'utf8');
assert.ok(renderer.includes('TaskForm className="motivo-derrota-form" progressive'), 'deve utilizar o mesmo formulário progressivo das demais tarefas');
assert.ok(renderer.includes('TaskQuestion number="01" stage="Motivo da derrota"'), 'primeira etapa mostra seletor Benner');
assert.ok(renderer.includes('TaskQuestion number="02" stage="Natureza da derrota"'), 'segunda etapa pede natureza');
assert.ok(renderer.includes('QaOptionGroup'), 'natureza utiliza cartões do Q&A');
assert.ok(renderer.includes('data-qa-answered={motivoValido'), 'não pode avançar com opção ausente do catálogo');
assert.ok(renderer.includes('submitLabel="Cadastrar no Benner"'), 'envio deve ser específico da operação');
assert.ok(renderer.includes("setNatureza(null)"), 'natureza não deve ser presumida a partir da classificação');
assert.ok(!renderer.includes('Motivo da derrota\\n      <textarea'), 'não pode oferecer texto livre');
assert.ok(workflow.includes("[data-qa-answered]"), 'Q&A deve reconhecer o SelectMenu autorizado');
assert.ok(workflow.includes('onSkip?: () => void'), 'motivo não deve oferecer pulo');
assert.ok(station.includes('form.motivo-derrota-form[data-qa-progressive'), 'deve herdar o layout progressivo');
assert.ok(!station.includes('.motivo-derrota-card-heading'), 'não deve existir layout paralelo ao workspace');
